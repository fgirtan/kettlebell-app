const { chromium, devices } = require('playwright');
(async()=>{const S=process.argv[2];const b=await chromium.launch();const c=await b.newContext({...devices['iPhone 13'],colorScheme:'dark'});
const p=await c.newPage();const errs=[];p.on('pageerror',e=>errs.push(e.message));p.on('console',m=>{if(m.type()==='error')errs.push(m.text())});
const W=()=>p.waitForTimeout(700);
await p.goto('http://localhost:8765/');await p.waitForTimeout(500);
await p.tap('#kbMode [data-v=custom]');await W();await p.tap('#cwNew');await W();await p.tap('#cwAdd');await W();
await p.fill('#sheet .search','goblet squat');await W();
await p.tap('#pkList .ex-item .thumb');await W();
const detail=await p.evaluate(()=>{const s=document.querySelector('#sheet2');return s&&!s.hidden?s.querySelector('h2').textContent:'none'});
const pickerStill=await p.evaluate(()=>!document.querySelector('#sheet').hidden);
const added0=await p.textContent('#pkCount');
await p.screenshot({path:S+'/pk-detail.png'});
await p.tap('#shAdd');await W();
const after=await p.evaluate(()=>[document.querySelector('#sheet2').hidden, document.querySelector('#pkCount').textContent]);
await p.tap('#pkList .ex-item .icon-btn');await W();
const plus=await p.textContent('#pkCount');
await p.tap('#pkDone');await W();
const rows=await p.$$eval('.cw-row .cw-name',r=>r.map(x=>x.textContent));
console.log('tap picture -> detail:',detail,'| picker still open:',pickerStill,'| added after picture tap:',added0,'\nafter "Add to workout":',JSON.stringify(after),'\nafter +:',plus,'\nworkout rows:',JSON.stringify(rows),'\nerrors:',errs.join('\n')||'none');await b.close();})();
