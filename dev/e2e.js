const { chromium, devices } = require('playwright');
(async()=>{const S=process.argv[2];const b=await chromium.launch();const c=await b.newContext({...devices['iPhone 13'], colorScheme:'dark'});
const p=await c.newPage();const errs=[];p.on('pageerror',e=>errs.push(e.message));p.on('console',m=>{if(m.type()==='error')errs.push(m.text())});
p.on('dialog',d=>d.accept());
await p.goto('http://localhost:8765/');await p.waitForTimeout(500);
await p.click('#tToggle');await p.waitForTimeout(200);
await p.click('[data-step=restEvery][data-d="1"]');await p.click('[data-step=prep][data-d="5"]');
await p.click('[data-seg=warmMin] button[data-v="3"]');
await p.locator('#timingCard').screenshot({path:S+'/b-timing.png'});
await p.click('#gen');await p.waitForTimeout(800);
await p.screenshot({path:S+'/b-preview.png'});
const startTxt=await p.textContent('.sticky-start button');
await p.click('.sticky-start button');await p.waitForTimeout(1000);
await p.screenshot({path:S+'/b-player.png'});
await p.click('[data-skip=skipWarm]');await p.waitForTimeout(800);
await p.screenshot({path:S+'/b-player2.png'});
await p.click('[data-skip=startNow]');await p.waitForTimeout(800);
await p.screenshot({path:S+'/b-player3.png'});
const info=await p.evaluate(()=>({phase:document.querySelector('.p-phase').textContent,name:document.querySelector('.p-name').textContent}));
await p.click('#pClose');await p.waitForTimeout(300);
await p.click('[data-tab=library]');await p.waitForTimeout(300);await p.click('#libList .ex-item .info');await p.waitForTimeout(600);await p.screenshot({path:S+'/b-sheet.png'});
console.log(startTxt.trim(),JSON.stringify(info),'errors:',errs.join('\n')||'none');await b.close();})();
