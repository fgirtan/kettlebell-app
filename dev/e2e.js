const { chromium, devices } = require('playwright');
(async()=>{const S=process.argv[2];const b=await chromium.launch();const c=await b.newContext({...devices['iPhone 13'], colorScheme:'dark'});
const p=await c.newPage();const errs=[];p.on('pageerror',e=>errs.push(e.message));p.on('console',m=>{if(m.type()==='error')errs.push(m.text())});
await p.goto('http://localhost:8765/');await p.waitForTimeout(500);
await p.screenshot({path:S+'/a-home.png'});
await p.click('#gen');await p.waitForTimeout(800);
await p.screenshot({path:S+'/a-preview.png'});
await p.screenshot({path:S+'/a-preview-full.png',fullPage:true});
await p.click('.sticky-start button');await p.waitForTimeout(1200);
await p.screenshot({path:S+'/a-player.png'});
for(let i=0;i<6;i++){await p.click('#pNext');await p.waitForTimeout(150);} await p.waitForTimeout(700);
await p.screenshot({path:S+'/a-player2.png'});
p.on('dialog',d=>d.accept());await p.click('#pClose');await p.waitForTimeout(300);
await p.click('[data-tab=library]');await p.waitForTimeout(400);await p.screenshot({path:S+'/a-lib.png'});
await p.click('#libList .ex-item .info');await p.waitForTimeout(900);await p.screenshot({path:S+'/a-sheet.png'});
await p.click('#shClose');await p.click('[data-tab=history]');await p.waitForTimeout(300);await p.screenshot({path:S+'/a-hist.png'});
await p.click('[data-tab=settings]');await p.waitForTimeout(300);await p.screenshot({path:S+'/a-set.png'});
const sw=await p.evaluate(()=>navigator.serviceWorker.getRegistration().then(r=>!!r));
console.log('sw',sw,'errors:',errs.join('\n')||'none');await b.close();})();
